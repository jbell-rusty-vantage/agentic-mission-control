"""Generate the lane describe refresh section of migration 0040 from the declared matrices.

The section revises the `mission_control.lane_profile` describe documents of the profiles in
``REFRESHED_PROFILES`` to ``DECLARED_LANE_MATRICES``
(``src/mission_control/application/execution/harness/describe.py``), serialized exactly as
0030 and 0031 serialized their seeds:
``json.dumps(describe.model_dump(mode="json"), sort_keys=True, separators=(",", ":"))``.
Run from the Mission Control repository root (``SCRIPTS`` =
``packages/mission-control-db-contract/scripts``):

    uv run --no-sync python SCRIPTS/lane_describe_refresh.py --check
    uv run --no-sync python SCRIPTS/lane_describe_refresh.py --write

``--check`` exits 1 when the migration section differs from what the code declares.
``--write`` rewrites only the delimited section. It is allowed ONLY while 0040 is unreleased
(no deployment lock pins it and no receipt names it): an applied migration is immutable, so a
later describe change needs a new migration (and a new component version), never an edit here.
``tests/unit/harness/test_lane_contracts.py`` fails when the SQL drifts from the code.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

PACKAGE = Path(__file__).resolve().parents[1]
MIGRATION = PACKAGE / "component" / "migrations" / "0040_implemented_lane_describes.sql"
REFRESHED_PROFILES: tuple[str, ...] = (
    "cursor_local",
    "cursor_cloud",
    "claude_agent_sdk",
    "codex",
    "claude_managed",
    "codex_agents",
)
SECTION_BEGIN = "-- section: lane describe refresh"
SECTION_END = "-- end section: lane describe refresh"
DOLLAR_TAG = "$lane_describes$"

_HEADER = """\
-- section: lane describe refresh (materialization-observation run 1, release 1.4.0)
-- GENERATED by packages/mission-control-db-contract/scripts/lane_describe_refresh.py.
-- Existing 0030/0031/0033/0036 migration bytes remain immutable. This additive revision
-- publishes the implemented lane descriptions, including Managed Agents and Agents API.
-- A feature implementation is not live qualification. The qualification columns remain
-- false/NULL/NULL; a qualified row causes a refusal, never an overwrite.
-- Lift FORCE only for the table-owning migrator, disable only the reference-data guard,
-- then restore both. Runtime roles retain SELECT-only access to this reference table.
ALTER TABLE mission_control.lane_profile NO FORCE ROW LEVEL SECURITY;
ALTER TABLE mission_control.lane_profile DISABLE TRIGGER lane_profile_immutable;
DO $lane_describes$
DECLARE
    refreshed bigint;
BEGIN
"""

_UPDATE = """\
    UPDATE mission_control.lane_profile
       SET describe = '{literal}'::jsonb
     WHERE lane_profile = '{profile}' AND NOT qualified;
    GET DIAGNOSTICS refreshed = ROW_COUNT;
    IF refreshed <> 1 THEN
        RAISE EXCEPTION 'lane_profile {profile} was not refreshed (% rows)', refreshed
            USING ERRCODE = 'data_exception';
    END IF;
"""

_FOOTER = """\
END
$lane_describes$;
ALTER TABLE mission_control.lane_profile ENABLE TRIGGER lane_profile_immutable;
ALTER TABLE mission_control.lane_profile FORCE ROW LEVEL SECURITY;
-- end section: lane describe refresh
"""


_SUCCESSOR_HEADER = """\
-- section: lane describe successor ({label})
-- GENERATED by packages/mission-control-db-contract/scripts/lane_describe_refresh.py
-- (render_successor_section). Earlier migration bytes remain immutable. Each revision is
-- conditional on the exact describe the previous release persisted, so a drifted row refuses
-- instead of being overwritten; a qualified row is revised only where this release names it.
ALTER TABLE mission_control.lane_profile NO FORCE ROW LEVEL SECURITY;
ALTER TABLE mission_control.lane_profile DISABLE TRIGGER lane_profile_immutable;
DO $lane_describes$
BEGIN
"""

_SUCCESSOR_UPDATE = """\
    UPDATE mission_control.lane_profile
       SET describe = '{new}'::jsonb
     WHERE lane_profile = '{profile}' AND {qualified} AND describe = '{old}'::jsonb;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'lane_profile {profile} describe differs from {label}'
            USING ERRCODE = 'data_exception';
    END IF;
"""

_SUCCESSOR_FOOTER = """\
END
$lane_describes$;
ALTER TABLE mission_control.lane_profile ENABLE TRIGGER lane_profile_immutable;
ALTER TABLE mission_control.lane_profile FORCE ROW LEVEL SECURITY;
-- end section: lane describe successor
"""

_SEED_PATTERN = re.compile(r"\('([a-z_]+)', '[a-z_]+', '[a-z_]+',\s*'(\{.*?\})'::jsonb")
_REVISION_PATTERN = re.compile(
    r"UPDATE mission_control\.lane_profile\s+SET describe = '((?:[^']|'')*)'::jsonb\s+"
    r"WHERE lane_profile = '([a-z_]+)' AND (?:NOT )?qualified"
    r"(?: AND describe = '(?:[^']|'')*'::jsonb)?;"
)


def seeded_describes(sql: str) -> dict[str, dict[str, Any]]:
    """The describe documents a migration INSERTs into `lane_profile`, by profile."""

    return {match.group(1): json.loads(match.group(2)) for match in _SEED_PATTERN.finditer(sql)}


def revised_describes(sql: str) -> dict[str, dict[str, Any]]:
    """The describe documents a migration UPDATEs on `lane_profile`, by profile."""

    revised: dict[str, dict[str, Any]] = {}
    for match in _REVISION_PATTERN.finditer(sql):
        if match.group(2) in revised:
            raise ValueError(f"{match.group(2)} revised twice in one migration")
        revised[match.group(2)] = json.loads(match.group(1).replace("''", "'"))
    return revised


def persisted_documents(migrations: Path) -> dict[str, dict[str, Any]]:
    """The describe each profile holds after every migration of `migrations` applied in order."""

    documents: dict[str, dict[str, Any]] = {}
    for path in sorted(migrations.glob("[0-9][0-9][0-9][0-9]_*.sql")):
        sql = path.read_bytes().decode("utf-8")
        documents.update(seeded_describes(sql))
        documents.update(revised_describes(sql))
    return documents


def render_successor_section(
    *,
    label: str,
    documents: Mapping[str, Mapping[str, Any]],
    prior: Mapping[str, Mapping[str, Any]],
    profiles: tuple[str, ...],
    qualified_profiles: tuple[str, ...] = (),
) -> str:
    """A guarded revision of `profiles` from their `prior` persisted describe to `documents`.

    Every UPDATE names the exact prior literal (the 0042 pattern); a profile in
    `qualified_profiles` is revised with `qualified` instead of `NOT qualified`, which is the
    only way a qualified row's describe moves (the release names it explicitly).
    """

    parts = [_SUCCESSOR_HEADER.format(label=label)]
    for profile in profiles:
        document = documents[profile]
        previous = prior[profile]
        if document.get("lane_profile") != profile:
            raise ValueError(f"{profile}: describe must name its profile")
        qualified = profile in qualified_profiles
        declared = (bool(document.get("qualified")), bool(previous.get("qualified")))
        if declared != (qualified, qualified):
            raise ValueError(f"{profile}: qualification differs from the release's declaration")
        if document == previous:
            raise ValueError(f"{profile}: the declared describe equals the persisted one")
        new = describe_literal(document)
        old = describe_literal(previous)
        if DOLLAR_TAG in new or DOLLAR_TAG in old:
            raise ValueError(f"{profile}: describe contains the section dollar-quote tag")
        parts.append(
            _SUCCESSOR_UPDATE.format(
                new=new.replace("'", "''"),
                old=old.replace("'", "''"),
                profile=profile,
                qualified="qualified" if qualified else "NOT qualified",
                label=label,
            )
        )
    parts.append(_SUCCESSOR_FOOTER)
    return "".join(parts)


def describe_literal(document: Mapping[str, Any]) -> str:
    """The compact JSON 0030/0031 used for a describe seed (sorted keys, no spaces)."""

    return json.dumps(document, sort_keys=True, separators=(",", ":"))


def render_section(documents: Mapping[str, Mapping[str, Any]]) -> str:
    """The full delimited section for ``REFRESHED_PROFILES`` (``documents`` maps profile to the
    JSON-mode describe document)."""

    parts = [_HEADER]
    for profile in REFRESHED_PROFILES:
        document = documents[profile]
        if document.get("lane_profile") != profile or document.get("qualified") is not False:
            raise ValueError(f"{profile}: describe must name its profile and be unqualified")
        literal = describe_literal(document)
        if DOLLAR_TAG in literal:
            raise ValueError(f"{profile}: describe contains the section dollar-quote tag")
        parts.append(_UPDATE.format(literal=literal.replace("'", "''"), profile=profile))
    parts.append(_FOOTER)
    return "".join(parts)


def declared_documents() -> dict[str, dict[str, Any]]:
    from mission_control.application.execution.harness.describe import DECLARED_LANE_MATRICES

    return {
        profile: describe.model_dump(mode="json")
        for profile, describe in DECLARED_LANE_MATRICES.items()
    }


def current_section(sql: str) -> str:
    start = sql.index(SECTION_BEGIN)
    end = sql.index(SECTION_END, start) + len(SECTION_END)
    if sql[end : end + 1] == "\n":
        end += 1
    return sql[start:end]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail when the SQL drifted")
    mode.add_argument("--write", action="store_true", help="rewrite the section (unreleased only)")
    mode.add_argument("--print", action="store_true", help="print the generated section")
    args = parser.parse_args(argv)
    expected = render_section(declared_documents())
    if args.print:
        sys.stdout.write(expected)
        return 0
    sql = MIGRATION.read_bytes().decode("utf-8") if MIGRATION.exists() else expected
    actual = current_section(sql)
    if args.check:
        if actual != expected:
            sys.stderr.write(
                f"{MIGRATION.name}: lane describe section differs from DECLARED_LANE_MATRICES\n"
            )
            return 1
        sys.stdout.write("lane describe section matches DECLARED_LANE_MATRICES\n")
        return 0
    MIGRATION.write_bytes(sql.replace(actual, expected, 1).encode("utf-8"))
    sys.stdout.write(f"rewrote the lane describe section of {MIGRATION.name}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
