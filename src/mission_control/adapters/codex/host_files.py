"""The Codex profiles' Host Projection writer (SPEC-01; MP-03; moved here by OC-R3).

`codex`: the mission instruction is `thread/start.developerInstructions` (in `send_options`,
no file, so the repository's `AGENTS.md` loads as is); MCP servers are `.codex/config.toml`
`mcp_servers` with `env_vars` (Codex forwards variables by name only), hooks
`.codex/hooks.json`, custom agents TOML files under `.codex/agents/`; every project `.codex/`
entry needs project trust. `codex_cloud` reads the checked-out repository's AGENTS files and
skills only: a delimited mission section in `AGENTS.override.md` that layering merges after the
repository's own `AGENTS.md`, and every MCP server, hook and subagent reported, not dropped.
The hook runner and the gate answer in this package's `hook_output.py`. The lane-neutral
checks, reports and helpers are `application/agentic_components/projections.py`; bootstrap
composes `HOST_FILES`.
"""

