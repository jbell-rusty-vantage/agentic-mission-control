HOOK_OUTPUT_SOURCE: Final = Path(__file__).with_name("hook_output.py")


class CodexHostFiles:
    """`LaneHostFiles` of `codex` (worker-hosted app-server)."""

    kernel_surface: KernelSurface = "native_hook"

    def write(self, inputs: ProjectionInputs, state: ProjectionState) -> InProcessProjection | None:
        write_skills(inputs.skills, state.layering.skills, state)
        if state.telemetry:
            write_telemetry_pack(inputs.skills, state)
        write_hook_scripts(inputs.hooks, state)
        place_native_output(inputs.hooks, state, HOOK_OUTPUT_SOURCE)
        _codex(
            inputs.servers,
            inputs.hooks,
            inputs.agents,
            inputs.kernel_hooks,
            inputs.instructions,
            state,
        )
        return None


class CodexCloudHostFiles:
    """`LaneHostFiles` of `codex_cloud`: no Kernel Hook surface (reported wholesale)."""

    kernel_surface: KernelSurface = "none"

    def write(self, inputs: ProjectionInputs, state: ProjectionState) -> InProcessProjection | None:
        write_skills(inputs.skills, state.layering.skills, state)
        instructions = inputs.instructions
        if state.telemetry:
            write_telemetry_pack(inputs.skills, state)
            instructions = f"{instructions}\n\n{ADVISORY_INSTRUCTION}"
        _codex_cloud(
            inputs.servers,
            inputs.hooks,
            inputs.agents,
            inputs.kernel_hooks,
            instructions,
            state,
        )
        return None


def _toml(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list | tuple):
        return "[" + ", ".join(_toml(item) for item in value) + "]"
    if isinstance(value, dict):
        return (
            "{ " + ", ".join(f"{json.dumps(str(k))} = {_toml(v)}" for k, v in value.items()) + " }"
        )
    return json.dumps(str(value), ensure_ascii=False)


def _codex_config(servers: Sequence[ResolvedCapability], lane: LaneProfile) -> str:
    lines = ["# Generated by Mission Control Host Projection (SPEC-01). Do not edit."]
    for row in sorted(servers, key=file_server_name):
        launch = mcp_launch(row, lane)
        lines.extend(("", f"[mcp_servers.{json.dumps(file_server_name(row))}]"))
        if launch.transport == "stdio":
            lines.append(f"command = {_toml(launch.command)}")
            if launch.args:
                lines.append(f"args = {_toml(list(launch.args))}")
            if launch.env:
                lines.append(f"env = {_toml(dict(sorted(launch.env.items())))}")
            names = sorted(set(launch.env_refs) | set(launch.env_refs.values()))
            # Codex forwards variables by name only; there is no string interpolation, so the
            # environment name must equal the secret ref (renamed refs are forwarded as-is).
            if names:
                lines.append(f"env_vars = {_toml(names)}")
        else:
            lines.append(f"url = {_toml(launch.url)}")
            auth = {h: r for h, r in launch.header_refs.items() if h.lower() == "authorization"}
            other = {h: r for h, r in launch.header_refs.items() if h.lower() != "authorization"}
            if auth:
                lines.append(f"bearer_token_env_var = {_toml(next(iter(auth.values())))}")
            if other:
                lines.append(f"env_http_headers = {_toml(dict(sorted(other.items())))}")
        lines.append("enabled = true")
        if launch.tools:
            lines.append(f"enabled_tools = {_toml(list(launch.tools))}")
    return "\n".join(lines) + "\n"


def _codex(
    servers: Sequence[ResolvedCapability],
    hooks: Sequence[ResolvedCapability],
    agents: Sequence[ResolvedCapability],
    kernel_hooks: Sequence[KernelHook],
    instructions: str,
    state: ProjectionState,
) -> None:
    lane, layout, layering = state.lane, state.layout, state.layering
    # `thread/start.developerInstructions`: no file, so the repository's AGENTS.md loads as is.
    state.send_options[layering.overlay] = instructions
    # Codex loads the project `.codex/` layer (config.toml, hooks, agents) only for a trusted
    # project (learn.chatgpt.com/docs/config-file/config-advanced), so each entry needs trust.
    if servers:
        assert layout.mcp_file is not None
        state.write(layout.mcp_file, _codex_config(servers, lane))
        state.environment_names.update(mcp_environment_names(servers, lane, by_name=True))
        state.requires_trust.extend(row.definition.logical_id for row in servers)
    telemetry = state.telemetry_hooks
    settings = matcher_hooks(lane, kernel_hooks, hooks, telemetry, exec_form=False)
    if settings:
        assert layout.hooks_file is not None
        state.write(layout.hooks_file, dumps_json({"hooks": settings}))
        state.requires_trust.extend(
            entry.hook_id for entry in hook_entries(lane, kernel_hooks, hooks, telemetry)
        )
    for row in agents:
        profile = subagent(row).profile
        state.write(subagent_path(layering, profile.name), _codex_agent_toml(row, lane))
        state.requires_trust.append(row.definition.logical_id)


def _codex_agent_toml(row: ResolvedCapability, lane: LaneProfile) -> str:
    """A Codex custom agent file: `name`, `description`, `developer_instructions` plus config
    keys (learn.chatgpt.com/docs/agent-configuration/subagents). Settings it omits inherit
    from the parent session; `_report_subagent_fields` names them."""
    profile = subagent(row).profile
    lines = [
        "# Generated by Mission Control Host Projection (SPEC-01). Do not edit.",
        f"name = {_toml(profile.name)}",
        f"description = {_toml(profile.description)}",
    ]
    model = subagent_model(row, lane)
    if model != "inherit":
        lines.append(f"model = {_toml(model)}")
    if profile.readonly:
        lines.append(f"sandbox_mode = {_toml('read-only')}")
    lines.append(f"developer_instructions = {_toml(subagent_prompt(row))}")
    return "\n".join(lines) + "\n"


def _codex_cloud(
    servers: Sequence[ResolvedCapability],
    hooks: Sequence[ResolvedCapability],
    agents: Sequence[ResolvedCapability],
    kernel_hooks: Sequence[KernelHook],
    instructions: str,
    state: ProjectionState,
) -> None:
    """Codex Cloud reads the checked-out repository's AGENTS files and skills only: a task
    carries no per-task MCP, hook, approval or sandbox configuration, and no command/local
    hooks run under cloud orchestration (docs/qualification/lanes/codex_cloud/FEASIBILITY.md).
    Everything else is reported, not silently dropped.

    No per-task instruction override exists either, so the overlay is the delimited mission
    section of ``AGENTS.override.md``. Layering puts the repository's ``AGENTS.md`` first (the
    override replaces it for that directory) and swaps the section for a pointer at the
    operating contract when the merge would exceed the 32 KiB Codex limit."""
    section = mission_section(instructions)
    size = len(section.encode("utf-8"))
    limit = state.layout.instructions_limit
    if limit is not None and size > limit:
        state.overflow.append(
            f"mission section is {size} bytes; Codex reads at most {limit}, "
            f"so AGENTS.override.md points at {OPERATING_CONTRACT_PATH} instead"
        )
    state.write(state.layering.overlay, section)
    state.write(OPERATING_CONTRACT_PATH, instructions)
    state.degraded.extend(
        f"{server_name(row)}: codex_cloud accepts no per-task MCP configuration; configure "
        "the server on the Codex Cloud environment"
        for row in sorted(servers, key=server_name)
    )
    state.degraded.extend(
        f"{hook.hook_id}: codex_cloud runs no command hooks under cloud orchestration"
        for hook in kernel_hooks
    )
    for row in hooks:
        state.skipped.append(row.pin.render())
    for row in agents:
        state.skipped.append(row.pin.render())


