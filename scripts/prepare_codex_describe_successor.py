"""Prepare isolated 1.4.1 candidate inputs; never build, apply or rewrite release 1.4.0."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
from pathlib import Path

from mission_control_db_contract.canonical import digest_value

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "packages/mission-control-db-contract"
BASE_MANIFEST_SHA256 = "7ba8ec65917f99e8d16feb5c93835fe2495d82dee942327d06c33ee23b3b84d1"
MIGRATION = "0042_codex_01621_lane_describe.sql"


def frozen_inputs() -> tuple[dict, dict]:
    base = PACKAGE / "component"
    manifest_bytes = (base / "manifest.json").read_bytes()
    if hashlib.sha256(manifest_bytes).hexdigest() != BASE_MANIFEST_SHA256:
        raise ValueError("candidate requires the exact frozen release 1.4.0")
    manifest = json.loads(manifest_bytes)
    expected = {item["path"]: item["sha256"] for item in manifest["ordered_migrations"]}
    actual = {}
    for path in (base / "migrations").iterdir():
        if path.is_symlink() or path.is_junction() or not path.is_file():
            raise ValueError("frozen migrations must be regular files")
        actual[path.relative_to(base).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != expected:
        raise ValueError("frozen migration set or bytes differ from release 1.4.0")
    spec_path = base / "release-spec.json"
    spec = json.loads(spec_path.read_bytes())
    descriptor = manifest["runtime_descriptor"]
    if spec["runtime_descriptor_path"] != descriptor["path"]:
        raise ValueError("frozen runtime descriptor reference differs")
    descriptor_path = base / descriptor["path"]
    if descriptor_path.is_symlink() or not descriptor_path.is_file():
        raise ValueError("frozen runtime descriptor must be a regular file")
    descriptor_hash = hashlib.sha256(descriptor_path.read_bytes()).hexdigest()
    if descriptor_hash != descriptor["sha256"]:
        raise ValueError("frozen runtime descriptor bytes differ")
    source = {
        **actual,
        "release-spec.json": hashlib.sha256(spec_path.read_bytes()).hexdigest(),
        descriptor["path"]: descriptor_hash,
    }
    if digest_value(source) != manifest["source_inputs_digest"]:
        raise ValueError("frozen release-spec/source inputs differ")
    return manifest, spec


def _persisted_codex_describe_through_1130() -> dict:
    """The Codex describe `mission_control.lane_profile` holds after release 1.13.0."""

    import importlib.util

    spec = importlib.util.spec_from_file_location(
        "lane_describe_refresh", PACKAGE / "scripts/lane_describe_refresh.py"
    )
    assert spec is not None and spec.loader is not None
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    documents = generator.persisted_documents(PACKAGE / "releases/1.13.0/component/migrations")
    return json.loads(json.dumps(documents["codex"]))


def candidate_sql() -> str:
    source = (PACKAGE / "component/migrations/0040_implemented_lane_describes.sql").read_text()
    matches = re.findall(
        r"UPDATE mission_control\.lane_profile\s+SET describe = '((?:[^']|'')*)'::jsonb\s+"
        r"WHERE lane_profile = 'codex' AND NOT qualified;",
        source,
    )
    if len(matches) != 1:
        raise ValueError("expected exactly one frozen Codex describe")
    original = json.loads(matches[0].replace("''", "'"))
    # Release 1.4.3 (0046) added `subagents.fields` and `time_travel` after 0042 was built, and
    # release 1.14.0 (0073, cross-provider control) moved the declared Codex describe on; the
    # 1.4.1 candidate reproduces the describe as it stood at 0042: the document persisted through
    # 1.13.0 (0046 included) without the 0046 fields.
    current = _persisted_codex_describe_through_1130()
    current["subagents"].pop("fields", None)
    current.pop("time_travel", None)
    expected = json.loads(json.dumps(original).replace("codex-cli 0.162.0", "codex-cli 0.162.1"))
    expected["versions"]["codex_cli"] = "0.162.1"
    if current != expected or current["qualified"] is not False:
        raise ValueError("candidate scope permits only the unqualified Codex SDK version change")
    old = json.dumps(original, sort_keys=True, separators=(",", ":")).replace("'", "''")
    new = json.dumps(current, sort_keys=True, separators=(",", ":")).replace("'", "''")
    return f"""-- PROPOSED release 1.4.1. Unbuilt and unapplied; preserves 0040 and qualification.
-- Generated by scripts/prepare_codex_describe_successor.py; exact prior describe required.
ALTER TABLE mission_control.lane_profile NO FORCE ROW LEVEL SECURITY;
ALTER TABLE mission_control.lane_profile DISABLE TRIGGER lane_profile_immutable;
DO $codex_describe$
BEGIN
    UPDATE mission_control.lane_profile
       SET describe = '{new}'::jsonb
     WHERE lane_profile = 'codex' AND NOT qualified AND describe = '{old}'::jsonb;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Codex describe differs from unqualified release 1.4.0'
            USING ERRCODE = 'data_exception';
    END IF;
END
$codex_describe$;
ALTER TABLE mission_control.lane_profile ENABLE TRIGGER lane_profile_immutable;
ALTER TABLE mission_control.lane_profile FORCE ROW LEVEL SECURITY;
"""


def prepare(destination: Path) -> Path:
    base = PACKAGE / "component"
    manifest, spec = frozen_inputs()
    sql = candidate_sql()
    destination = destination.resolve()
    if destination == PACKAGE.resolve() or PACKAGE.resolve() in destination.parents:
        raise ValueError("candidate destination must be outside the frozen source package")
    # A fresh directory prevents overwriting the component, a previous proposal or user files.
    destination.mkdir(parents=True, exist_ok=False)
    component = destination / "component"
    shutil.copytree(base / "migrations", component / "migrations")
    shutil.copytree(PACKAGE / "runtime", destination / "runtime")
    spec["component_version"] = "1.4.1"
    fingerprint = manifest["schema_fingerprint"]
    if fingerprint not in spec["compatible_previous_fingerprints"]:
        spec["compatible_previous_fingerprints"].append(fingerprint)
    (component / "release-spec.json").write_text(json.dumps(spec, indent=2) + "\n")
    (component / "migrations" / MIGRATION).write_text(sql, newline="\n")
    # No manifest/generated contract is copied: candidate inputs cannot pose as a built release.
    return component


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    print(json.dumps({"candidate_component": str(prepare(args.out)), "state": "unbuilt"}))


if __name__ == "__main__":
    main()
