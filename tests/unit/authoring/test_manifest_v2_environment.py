def test_a_child_cannot_widen_the_network() -> None:
    assert _overlay(document_of(), {"network": {"mode": "allow_all"}}) == {
        f"{NODE}/network/mode": "widens_authority"
    }
    assert _overlay(document_of(), {"network": {"allow": ["evil.example.org"]}}) == {
        f"{NODE}/network/allow/0": "widens_authority"
    }
    parent = document_of()
    parent["mission"]["environment"]["network"]["include_signal_ingress"] = False
    assert _overlay(parent, {"network": {"include_signal_ingress": True}}) == {
        f"{NODE}/network/include_signal_ingress": "widens_authority"
    }
    # An explicit null would fall back to the deployment's policy.
    assert _overlay(document_of(), {"network": None}) == {f"{NODE}/network": "widens_authority"}
    # Narrowing is fine: a subset, or closing the network (another mode replaces the policy).
    assert _overlay(document_of(), {"network": {"allow": []}}) == {}
    assert _overlay(document_of(), {"network": {"mode": "none"}}) == {}


def _kit_switch(
    egress: tuple[str, ...],
    *,
    mission_kit: bool = True,
    network: dict[str, Any] | None = None,
    lane: str | None = None,
) -> dict[str, str]:
    """Compile with node 0 switching to another kit whose resolved egress is ``egress``
    (and to ``lane`` on a local workspace when given)."""

    def change(document: dict[str, Any]) -> None:
        if not mission_kit:
            del document["mission"]["environment"]["kit"]
        overlay: dict[str, Any] = {"kit": {"pin": OTHER_KIT_PIN}}
        if network is not None:
            overlay["network"] = network
        if lane is not None:
            overlay["lane"] = lane
            overlay["execution_environment"] = {
                "kind": "local_workspace",
                "profile": "worker.linux.wsl",
            }
        document["mission"]["program"]["nodes"][0].setdefault("environment", {}).update(overlay)

    inputs = Inputs({KIT_PIN: KIT, OTHER_KIT_PIN: KitRequirements(egress=egress)})
    return blockers(compile_text(manifest(change=change), inputs))


def test_a_kit_switch_widens_only_by_hosts_the_parent_does_not_allow() -> None:
    # The domain no longer refuses a switch it cannot compare; compile compares the hosts.
    assert _overlay(document_of(), {"kit": {"pin": OTHER_KIT_PIN}}) == {}
    # A kit whose egress the parent's kit or allowlist already grants widens nothing.
    assert _kit_switch(("pypi.org",)) == {}
    assert _kit_switch(("api.firecrawl.dev", "registry.npmjs.org")) == {}
    # A host the parent never allowed is a widening at the node's kit pin.
    assert _kit_switch(("pypi.org", "evil.example.org")) == {f"{NODE}/kit/pin": "widens_authority"}
    # Changing lane as well does not reset the inherited policy.
    assert _kit_switch(("pypi.org", "evil.example.org"), lane="codex") == {
        f"{NODE}/kit/pin": "widens_authority"
    }
    assert _kit_switch(("pypi.org",), lane="codex") == {}
    # A mission that pins no kit grants no kit egress to a node that adds one.
    assert _kit_switch(("pypi.org",), mission_kit=False) == {f"{NODE}/kit/pin": "widens_authority"}
    # Without the new kit's egress the switch widens nothing (its requirement must then be
    # allowed explicitly); dropping or keeping the kit narrows or keeps the grant.
    assert _kit_switch(("api.firecrawl.dev",), network={"include_kit": False}) == {}
    assert _overlay(document_of(), {"kit": None}) == {}
    assert _overlay(document_of(), {"kit": {"pin": KIT_PIN}}) == {}


def test_a_child_cannot_add_secrets_beyond_the_grant() -> None:
    granted = {"name": "FIRECRAWL_API_KEY", "ref": "secret:firecrawl/api_key"}
    assert _overlay(document_of(), {"secrets": [granted]}) == {}
