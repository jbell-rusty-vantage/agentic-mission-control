@pytest.mark.parametrize("profile", list(PLACEMENTS))
def test_one_manifest_compiles_offline_for_every_profile(profile: str) -> None:
    inputs = Inputs()
    compilation = compile_text(manifest(profile), inputs)
    assert compilation.ok, blockers(compilation)
    # The kit resolved through the port, once; no provider was asked anything.
    assert inputs.calls == [KIT_PIN]
    (definition,) = compilation.definitions
    selections = definition.program.selections
    assert selections is not None
    assert selections.kit == KitSelection(pin=KIT_PIN)
    assert selections.secret_names == ("FIRECRAWL_API_KEY", "MC_SIGNAL_TOKEN")
    fields = selections.binding_fields()
    # The network policy needs the kit's egress and the installation's hosts: the launch
    # resolves it (MO-15), so the manifest alone yields no network_policy_ref.
    assert fields == {"setup_pin": KIT_PIN, "secret_refs": SECRET_REFS}
    # Every node role carries the inherited additions.
    for node in definition.program.nodes:
        assert node.selections is not None and node.selections.binding_fields() == fields
    # The committed definition round-trips with the additions and keeps its digest.
    stored = MissionDefinition.model_validate(definition.model_dump(mode="json"))
    assert stored.digest == definition.digest
    assert stored.program.selections == selections


