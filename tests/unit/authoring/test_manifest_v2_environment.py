def test_the_schema_and_the_model_agree_on_a_variable_source() -> None:
    schema = json.loads((SCHEMAS / "mc.mission_manifest.v2.json").read_text(encoding="utf-8"))
    validator = jsonschema.Draft202012Validator(
        {"$defs": schema["$defs"], "$ref": "#/$defs/EnvironmentVariable"}
    )
    cases: list[tuple[dict[str, Any], bool]] = [
        ({"name": "A", "value": "x"}, True),
        ({"name": "A", "value_ref": "config:a"}, True),
        ({"name": "A", "value": None, "value_ref": "config:a"}, True),
        ({"name": "A", "value": "x", "value_ref": None}, True),
        ({"name": "A", "value": "x", "value_ref": "config:a"}, False),
        ({"name": "A", "value": None, "value_ref": None}, False),
        ({"name": "A"}, False),
    ]
    for variable, valid in cases:
        assert validator.is_valid(variable) is valid, variable
        try:
            EnvironmentV2.model_validate({"variables": [variable]})
        except ValidationError:
            assert not valid, variable
        else:
            assert valid, variable
